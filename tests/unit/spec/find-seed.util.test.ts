/**
 * Seed finder (a utility, not a spec). Skipped in the normal suite; run it with `node scripts/find-seed.mjs`
 * (sets FIND_SEED=1). It plays the travel.md reference policy over the string seeds SEED-0..SEED-999
 * (the same string the UI turns into an Rng via seedFromString(?seed=)), writes tests/e2e/seeds.ts
 * and test-results/find-seed.json.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { applyAction, createGame, createRng, depart, policyIntent, policyShop, runPolicy, seedFromString } from '@/sim';

const COUNT = Number(process.env.FIND_SEED_COUNT ?? 1000);
const WANT = 3;
const opts = { profession: 'executive', window: 3 } as const;

/** Day on which the policy first reaches waypoint 1 (Lunar Debris Ring), or null within 40 days. */
function firstWaypointDay(seedText: string): number | null {
  const rng = createRng(seedFromString(seedText));
  let s = depart(policyShop(createGame({ ...opts }, rng)), rng).state;
  while (s.status === 'traveling' && s.day < 40) {
    s = applyAction(s, policyIntent(s), rng).state;
    if (s.arrivedAt === 1) return s.day;
  }
  return null;
}

describe.skipIf(!process.env.FIND_SEED)('find-seed', () => {
  it('searches SEED-0..SEED-999 and writes tests/e2e/seeds.ts', () => {
    // Deaths are collected over the whole range and the earliest WANT are kept: under the reference policy
    // no Executive (or Engineer/Farmer, Window 3) dies before day 40 in 1000 seeds; the earliest is around day 110.
    const deaths: { seed: string; day: number; cause: string }[] = [];
    const full: { seed: string; days: number; score: number }[] = [];
    const fast: { seed: string; day: number }[] = [];
    for (let i = 0; i < COUNT; i++) {
      const seed = `SEED-${i}`;
      const r = runPolicy(seedFromString(seed), opts);
      if (r.status === 'dead') deaths.push({ seed, day: r.days, cause: r.causes.join('+') });
      if (full.length < WANT && r.status === 'arrived' && r.deaths === 0) full.push({ seed, days: r.days, score: r.score });
      if (fast.length < WANT) {
        const d = firstWaypointDay(seed);
        if (d !== null && d <= 6) fast.push({ seed, day: d });
      }
    }
    const early = deaths.sort((a, b) => a.day - b.day).slice(0, WANT);
    mkdirSync('test-results', { recursive: true });
    writeFileSync('test-results/find-seed.json', JSON.stringify({ early, full, fast }, null, 2));
    const q = (xs: { seed: string }[]): string => xs.map((x) => `'${x.seed}'`).join(', ');
    const note = (xs: object[]): string => xs.map((x) => `//   ${JSON.stringify(x)}`).join('\n');
    writeFileSync('tests/e2e/seeds.ts', `/**
 * Known seeds for e2e tests, generated by \`node scripts/find-seed.mjs\` (tests/unit/spec/find-seed.util.test.ts).
 *
 * These are POLICY-RUN seeds: they describe what runPolicy(seedFromString(seed), { profession: 'executive', window: 3 })
 * does with the travel.md reference policy (3 drives, 10 suits, 5 boxes of charges, 1 of each part, rations with the rest;
 * Cruise, Half rations, rest below health 50, scan when low). The UI builds its Rng from the same string
 * (\`?seed=\` -> seedFromString), but a human or Playwright shopping list and intents will differ, so treat these as
 * "likely", not guaranteed. Re-run the finder if the sim's rng consumption changes.
 */

/**
 * Executive, Window 3: the EARLIEST policy deaths in SEED-0..SEED-999 (none die before day 40; the sim is forgiving early).
 * For a fast game-over in e2e, play badly in the UI (e.g. buy no rations) rather than rely on a seed.
 */
${note(early)}
export const EARLY_DEATH_SEEDS: readonly string[] = [${q(early)}];

/** Executive, Window 3: arrives with all five crew alive under the policy. */
${note(full)}
export const FULL_CREW_ARRIVAL_SEEDS: readonly string[] = [${q(full)}];

/** Executive, Window 3: the policy reaches the first waypoint (Lunar Debris Ring) within 6 days. */
${note(fast)}
export const FAST_FIRST_WAYPOINT_SEEDS: readonly string[] = [${q(fast)}];
`);
    expect(early.length).toBe(WANT);
    expect(full.length).toBe(WANT);
    expect(fast.length).toBe(WANT);
  }, 120000);
});
